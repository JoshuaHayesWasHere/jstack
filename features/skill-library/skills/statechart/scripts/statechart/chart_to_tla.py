"""chart-to-tla: writes a TLA+ spec, a TLC config, and a reader mapping from a Mermaid
stateDiagram-v2."""

import json
import os
import re
import sys
import unicodedata

from statechart.lib import ChartError, parse_mermaid

USAGE = "Usage: chart-to-tla CHART.mmd --module NAME [--dir OUT]"
HELP = f"""{USAGE}

Writes a TLA+ spec, a TLC config, and a reader mapping from a Mermaid stateDiagram-v2.
statechart from-chart runs it, then checks each INVARIANT in NAME.cfg alone.

Each region becomes one variable whose values are the region's states. Each transition label
becomes one action. Regions that share a label move together: every region that can take it does,
and the others stay. A "%% when" line after a transition is its guard: the region can take that
transition only while the other regions are in, or with "not" are not in, the states it names. An
unlabeled transition is its own action. Each
"%% never NAME: A & B -- sentence" line becomes the invariant NAME == ~(A /\\ B). A name in a
never line is a state, or a composite that stands for every state inside it.

  --module NAME  The TLA+ module name. Required.
  --dir OUT      The folder for the files. Default: the chart's folder.
  -h, --help     Print this help, and exit 0.

Writes NAME.tla, NAME.cfg, and NAME.map.py into OUT, and replaces files with those names.
NAME.cfg has SPECIFICATION Spec, INVARIANT TypeOK, and one INVARIANT per never line.
NAME.map.py gives tlc-to-chart the reader's words: the region states joined by " | ".

Exit codes
  0  It wrote the files.
  1  It cannot read the chart. The error says why.
  2  A bad argument."""
MORE = "Run chart-to-tla --help for the flags."
RESERVED = {"vars", "Init", "Next", "Spec", "TypeOK", "Settled"}


def tla_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tla_set(xs):
    return "{" + ", ".join(tla_string(x) for x in xs) + "}"


def write_spec(chart, module, directory):
    with open(chart, encoding="utf-8") as handle:
        parsed = parse_mermaid(handle.read())
    regions, nevers = parsed["regions"], parsed["nevers"]
    taken = set(RESERVED)

    def ident(words, lower):
        plain = unicodedata.normalize("NFKD", words)
        parts = [p for p in re.sub(r"[^A-Za-z0-9]+", " ", plain).strip().split(" ") if p]
        made = "".join(
            ((p[0].lower() if lower and i == 0 else p[0].upper()) + p[1:])
            for i, p in enumerate(parts)
        )
        made = made or "Step"
        if re.match(r"[0-9]", made):
            made = f"{'r' if lower else 'S'}{made}"
        unique = made
        n = 2
        while unique in taken:
            unique = f"{made}{n}"
            n += 1
        taken.add(unique)
        return unique

    variables = []
    for name, r in regions.items():
        if not r["states"]:
            raise ChartError(f"region {name} has no states")
        if not r["initial"]:
            raise ChartError(f"region {name} has no [*] --> start")
        variables.append({"name": name, "v": ident(name, True), **r})

    def guard_of(g):
        if not g:
            return None
        parts = []
        for name, states in g["states"].items():
            v = next(x for x in variables if x["name"] == name)["v"]
            parts.append(
                f"{v} = {tla_string(states[0])}"
                if len(states) == 1
                else f"{v} \\in {tla_set(states)}"
            )
        return f"~({' \\/ '.join(parts)})" if g["not"] else " /\\ ".join(parts)

    actions = []
    by_label = {}
    for ri, r in enumerate(variables):
        for t in r["transitions"]:
            a = by_label.get(t["label"]) if t["label"] else None
            if not a:
                a = {"label": t["label"], "moves": {}}
                actions.append(a)
                if t["label"]:
                    by_label[t["label"]] = a
            moves = a["moves"].setdefault(ri, [])
            when = guard_of(t.get("guard"))
            if not any(
                m["from"] == t["from"] and m["to"] == t["to"] and m["when"] == when for m in moves
            ):
                moves.append({"from": t["from"], "to": t["to"], "when": when})
    for a in actions:
        only = None if a["label"] else next(iter(a["moves"].values()))[0]
        a["name"] = ident(a["label"] or f"{only['from']} to {only['to']}", False)

    out = []

    def conjuncts(lines):
        return [f"    /\\ {line}" for line in lines]

    base = os.path.basename(chart)
    out.append(f"---- MODULE {module} ----")
    out.append(f"\\* Generated by chart-to-tla from {base}.")
    out.append("\\* Each region is one variable and each transition label is one action.")
    out.append("\\* Once you add guards and variables from the real code, this file is the source.")
    out.append(
        f"\\* statechart from-chart {base} keeps it, checks it, and compares it with the chart."
    )
    out.append("")
    names = [x["v"] for x in variables]
    out.append(f"VARIABLES {', '.join(names)}")
    out.append(f"vars == <<{', '.join(names)}>>")
    out.append("")
    for x in variables:
        out += [f"\\* Region {x['name']}", f"{x['v']}States == {tla_set(sorted(x['states']))}"]
    out.append("")
    out += ["TypeOK ==", *conjuncts(f"{x['v']} \\in {x['v']}States" for x in variables)]
    out.append("")
    out += [
        "Init ==",
        *conjuncts(
            f"{x['v']} = {tla_string(next(iter(x['initial'])))}"
            if len(x["initial"]) == 1
            else f"{x['v']} \\in {tla_set(x['initial'])}"
            for x in variables
        ),
    ]

    def enabled(v, m):
        return f"{v} = {tla_string(m['from'])}{' /\\ ' + m['when'] if m['when'] else ''}"

    def whether_takes(a, ri):
        v = variables[ri]["v"]
        moves = a["moves"][ri]
        if all(not m["when"] for m in moves):
            source = tla_set(dict.fromkeys(m["from"] for m in moves))
            return {"can": f"{v} \\in {source}", "cannot": f"{v} \\notin {source}"}
        either = " \\/ ".join(f"({enabled(v, m)})" for m in moves)
        return {"can": either, "cannot": f"~({either})"}

    for a in actions:
        out.append("")
        if a["label"]:
            out.append(f"\\* {a['label']}")
        out.append(f"{a['name']} ==")
        moving = list(a["moves"])
        shared = len(moving) > 1
        if shared:
            out.append(f"    /\\ ({' \\/ '.join(whether_takes(a, ri)['can'] for ri in moving)})")
        for ri in moving:
            v = variables[ri]["v"]
            ds = [f"({enabled(v, m)} /\\ {v}' = {tla_string(m['to'])})" for m in a["moves"][ri]]
            if shared:
                ds.append(f"({whether_takes(a, ri)['cannot']} /\\ UNCHANGED {v})")
            out.append(f"    /\\ \\/ {ds[0]}")
            out += [f"       \\/ {d}" for d in ds[1:]]
        still = [x["v"] for ri, x in enumerate(variables) if ri not in a["moves"]]
        if still:
            out.append(f"    /\\ UNCHANGED <<{', '.join(still)}>>")
    out.append("")
    out.append(
        f"Next == {' \\/ '.join(a['name'] for a in actions)}"
        if actions
        else "Next == UNCHANGED vars"
    )
    out.append("")
    out.append("Spec == Init /\\ [][Next]_vars")

    def resolve(item):
        hits = []
        for ri, x in enumerate(variables):
            inside = (
                [item]
                if item in x["states"]
                else [s for s in x["states"] if s.startswith(f"{item}.")]
            )
            if inside:
                hits.append({"ri": ri, "inside": inside})
        if not hits:
            raise ChartError(f'never line names "{item}", which is not a state in the chart')
        if len(hits) > 1:
            which = " and ".join(variables[h["ri"]]["name"] for h in hits)
            raise ChartError(
                f'never line names "{item}", which is a state in regions {which}; rename one'
            )
        return hits[0]

    invariants = []
    for n in nevers:
        if n["name"] in taken:
            raise ChartError(f"never name {n['name']} is already used in the spec")
        taken.add(n["name"])
        parts = [resolve(s) for s in n["states"]]
        if len({p["ri"] for p in parts}) != len(parts):
            raise ChartError(
                f"never {n['name']} names two states of one region; one region is in one state at a"
                " time"
            )
        cond = [
            f"{variables[p['ri']]['v']} = {tla_string(p['inside'][0])}"
            if len(p["inside"]) == 1
            else f"{variables[p['ri']]['v']} \\in {tla_set(p['inside'])}"
            for p in parts
        ]
        out.append("")
        if n["sentence"]:
            out.append(f"\\* {n['sentence']}")
        out.append(f"{n['name']} == ~({' /\\ '.join(cond)})")
        invariants.append(n["name"])
    out += ["", "====", ""]

    rules = ["TypeOK", *invariants]
    cfg = ["SPECIFICATION Spec", *(f"INVARIANT {r}" for r in rules), ""]

    labels = {a["name"]: a["label"] for a in actions}
    mapping = [
        f"# Generated by chart-to-tla from {base}. Reader states are the chart's own states.",
        f"regions = {json.dumps(names, ensure_ascii=False)}",
        f"LABELS = {json.dumps(labels, indent=4, ensure_ascii=False)}",
        "",
        "# The actions the reader takes. facts.settled needs them. Add cause() and detail() as the"
        " spec grows.",
        "reader_actions = []",
        "",
        "",
        "def state(v):",
        '    return " | ".join(str(v[r]) for r in regions)',
        "",
        "",
        "def step(action):",
        "    return LABELS.get(action, action)",
        "",
    ]

    os.makedirs(directory, exist_ok=True)
    for suffix, lines in ((".tla", out), (".cfg", cfg), (".map.py", mapping)):
        with open(os.path.join(directory, f"{module}{suffix}"), "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines))
    print(
        f"{module}: {len(variables)} region variable(s), {len(actions)} action(s), rules"
        f" {' '.join(rules)}"
        f" -> {os.path.normpath(os.path.join(directory, module))}.{{tla,cfg,map.py}}",
        file=sys.stderr,
    )


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    chart = module = directory = None
    i = 0
    while i < len(argv):
        a = argv[i]
        if a in ("-h", "--help"):
            print(HELP)
            return 0
        if a == "--module":
            i += 1
            module = argv[i] if i < len(argv) else None
        elif a == "--dir":
            i += 1
            directory = argv[i] if i < len(argv) else None
        elif not a.startswith("-") and not chart:
            chart = a
        else:
            print(f"unknown argument {a}. {MORE}", file=sys.stderr)
            return 2
        i += 1
    if not chart or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", module or ""):
        print(f"{USAGE}\n{MORE}", file=sys.stderr)
        return 2
    try:
        write_spec(
            chart, module, directory if directory is not None else os.path.dirname(chart) or "."
        )
    except ChartError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
