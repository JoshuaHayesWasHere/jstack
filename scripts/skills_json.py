"""Write `skills.json`, or with `--check` fail when it is stale: `skills_json.py [--check]`.

`skills.json` names every skill of skills/ and principle of principles/ for a brief's
`Skills:` line, and for any reader outside this repo: `jbriefs.skills` resolves names from it.
This builds it and writes it: `make skills-json`. With `--check` it writes nothing, and exits 1
when the file on disk is not what the build gives, naming the items that differ. `make check`
and `make check-fast` run that.

An item's source is read from the `Upstream map:` of `THIRD_PARTY.md` (`jdrift.read_section`),
the paths its file was written from, so there is no second list to keep. The build lives here
and not in `jbriefs.skills`, so the resolver does not import `jdrift`.

It needs only the standard library, so it runs before `uv sync`.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from jbriefs.skills import CATALOG  # noqa: E402
from jdrift import FILE as THIRD_PARTY  # noqa: E402
from jdrift import read_section  # noqa: E402

COMMENT = (
    "Generated by `make skills-json` from skills/, principles/ and the pstack map of "
    "THIRD_PARTY.md: do not edit. Each item is a name a brief's Skills: line may use. source: "
    "`pstack` is pstack's item of the same name, brought over one to one; `adapted` is built "
    "from pstack's item with other material, or from a pstack item of another name, which "
    "`pstack_name` gives; `josh` is jstack's own, with no pstack skill or principle behind it, "
    "though it may borrow a passage from a pstack reference file. THIRD_PARTY.md says what "
    "each took and what changed."
)
_UPSTREAM_SKILL = re.compile(r"pstack/skills/(?P<name>[^/]+)/SKILL\.md")


def item(name: str, kind: str, relative: str, upstream: tuple[str, ...]) -> dict[str, str]:
    """One item. pstack's item of the same name alone is `pstack`, with more beside it
    `adapted`; one pstack item of another name is `adapted` under that `pstack_name`; no
    pstack item at all is `josh`, whatever reference files it borrows from."""
    found = {"name": name, "kind": kind, "path": relative}
    items = [hit["name"] for path in upstream if (hit := _UPSTREAM_SKILL.fullmatch(path))]
    if name in items:
        found["source"] = "pstack" if len(upstream) == 1 else "adapted"
    elif items:
        found["source"] = "adapted"
        if len(items) == 1:
            found["pstack_name"] = items[0]
    else:
        found["source"] = "josh"
    return found


def render(root: Path = ROOT) -> str:
    """`skills.json`: every skill of skills/ and principle of principles/, by kind, then
    name."""
    fed: dict[str, list[str]] = {}
    for upstream, local in read_section((root / THIRD_PARTY).read_text()).sources.items():
        for path in local:
            fed.setdefault(path, []).append(upstream)
    files = [("skill", path.parent.name, path) for path in (root / "skills").glob("*/SKILL.md")]
    files += [("principle", path.stem, path) for path in (root / "principles").glob("*.md")]
    items = []
    for kind, name, path in sorted(files):
        relative = str(path.relative_to(root))
        items.append(item(name, kind, relative, tuple(fed.get(relative, ()))))
    return json.dumps({"$comment": COMMENT, "items": items}, indent=2) + "\n"


def main(argv: list[str]) -> int:
    path = ROOT / CATALOG
    built = render(ROOT)
    if argv != ["--check"]:
        if argv:
            print("usage: skills_json.py [--check]", file=sys.stderr)
            return 2
        path.write_text(built)
        print(f"wrote {CATALOG}: {len(json.loads(built)['items'])} items")
        return 0
    try:
        had = path.read_text()
    except FileNotFoundError:
        print(f"{CATALOG} is missing: run `make skills-json` and commit it", file=sys.stderr)
        return 1
    if had == built:
        return 0
    try:
        old = {each["name"]: each for each in json.loads(had)["items"]}
    except (ValueError, KeyError, TypeError):
        old = {}
    new = {each["name"]: each for each in json.loads(built)["items"]}
    differ = sorted(name for name in old.keys() | new.keys() if old.get(name) != new.get(name))
    named = ", ".join(differ) if differ else "its layout or comment"
    print(
        f"{CATALOG} is stale against skills/, principles/ and THIRD_PARTY.md "
        f"({named}): run `make skills-json` and commit it",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
