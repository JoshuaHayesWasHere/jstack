"""`skills.json`: every skill, principle, playbook and template, for `jbriefs.skills`. It also
lists every hook script, the status line and the git hooks. Each hook script comes with the
harnesses that run it and the entries the install writes for it. The install reads the file
to assemble each harness's layout (`jinstall.layout`) and to write each hook entry
(`jinstall.needs`), in a checkout and from a release's wheel alike.

A brief's `Skills:` line names a skill or a principle, or a playbook its feature lists as
`nameable`; the runtime finds every other file by kind and name (`jbriefs.skills.where`). This
module loads jdrift's own reader from jdrift's package, wherever the tree has that package.
With it, the module reads an item's `source` from the `Upstream map:` of `THIRD_PARTY.md`.
jdrift's `__init__` runs here, so it must import nothing but the standard library, as the
generator does.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path, PurePosixPath
from types import ModuleType

from jtrees.crawl import Invalid
from jtrees.model import Item, Tree

PATH = "skills.json"
COMMENT = (
    "Generated by scripts/generate-jstack-trees.py from features/, skills/, playbooks/, "
    "templates/ and the pstack map of THIRD_PARTY.md: do not edit. A skill or "
    "principle is a name a brief's Skills: line may use, and so is a playbook marked "
    "nameable. source: `pstack` is pstack's item of the same name, brought over one to one; "
    "`adapted` is built from pstack's item with other material, or from a pstack item of "
    "another name, which `pstack_name` gives; `josh` is jstack's own, with no pstack skill or "
    "principle behind it, though it may borrow a passage from a pstack reference file. "
    "THIRD_PARTY.md says what each took and what changed. hooks: each hook script, the "
    "harnesses that run it, which the install links into each harness's layout, and each "
    "settings entry the install writes for it. statusLine: the script the install sets as "
    "Claude Code's status line. gitHooks: each hook the install links into a main checkout. "
    "projectSkills: each skill of this repo's own, which the install links into a checkout's "
    ".claude/skills and .cursor/skills by its name."
)
_UPSTREAM_SKILL = re.compile(r"pstack/skills/(?P<name>[^/]+)/SKILL\.md")


def _jdrift(tree: Tree) -> ModuleType:
    package = tree.root / tree.feature("jdrift").packages[0]
    spec = importlib.util.spec_from_file_location("jtrees_jdrift", package / "__init__.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _source(name: str, upstream: tuple[str, ...]) -> dict[str, str]:
    """The source of the item `name`, from the pstack paths in `upstream`. An item that
    comes only from the pstack item of the same name is `pstack`, and one that comes from that item
    and from any other upstream path is `adapted`. An item from one pstack item of another name is
    `adapted`, with that item as its `pstack_name`. An item from no pstack item is `josh`."""
    items = [hit["name"] for path in upstream if (hit := _UPSTREAM_SKILL.fullmatch(path))]
    if name in items:
        return {"source": "pstack" if len(upstream) == 1 else "adapted"}
    if len(items) == 1:
        return {"source": "adapted", "pstack_name": items[0]}
    return {"source": "adapted" if items else "josh"}


def _entry(item: Item, upstream: tuple[str, ...]) -> dict[str, object]:
    entry: dict[str, object] = {"name": item.name, "kind": item.kind, "path": item.path}
    entry.update(_source(item.name, upstream))
    if item.description:
        entry["description"] = item.description
    if item.nameable:
        entry["nameable"] = True
    return entry


def entries(tree: Tree) -> list[dict[str, object]]:
    """Every item as `skills.json` lists it, with its `path` from the repo root."""
    jdrift = _jdrift(tree)
    third = Path(tree.root / jdrift.FILE).read_text(encoding="utf-8")
    fed: dict[str, list[str]] = {}
    for upstream, local in jdrift.read_section(third).sources.items():
        for path in local:
            fed.setdefault(path, []).append(upstream)
    return [_entry(item, tuple(fed.get(item.path, ()))) for item in tree.items]


def hooks(tree: Tree) -> list[dict[str, object]]:
    """Every script that a feature declares as an agent's hook or as its status line (only Claude
    Code has a status line). Each script comes with the harnesses that run it and with its install
    entries (`events`), in the order its feature declares them. Each entry gives its harness, event
    and matcher, and whether it refuses. A git hook belongs to the checkout, not to a harness, so
    this does not list it."""
    harnesses: dict[str, set[str]] = {}
    events: dict[str, list[dict[str, object]]] = {}
    for feature in tree.features:
        for hook in feature.hooks:
            harnesses.setdefault(hook.script, set()).update(hook.harnesses)
            for harness in hook.harnesses:
                event: dict[str, object] = {"harness": harness, "event": hook.event}
                event |= {"matcher": hook.matcher} if hook.matcher else {}
                event |= {"refuses": True} if hook.refuses else {}
                events.setdefault(hook.script, []).append(event)
        if feature.status_line:
            harnesses.setdefault(feature.status_line, set()).add("claude-code")
    listed = [
        {"name": PurePosixPath(script).name, "path": script, "harnesses": sorted(names)}
        | {"events": events.get(script, [])}
        for script, names in harnesses.items()
    ]
    # By name, which a move leaves as it is: a hook's lines change in place.
    return sorted(listed, key=lambda one: (one["name"], one["path"]))


def status_line(tree: Tree) -> dict[str, str] | None:
    """The one status line a feature declares, which the install sets in Claude Code's
    settings. It raises `Invalid` when two features declare one."""
    lines = [one.status_line for one in tree.features if one.status_line]
    if len(lines) > 1:
        raise Invalid([f"{PATH}: two features declare a status line: {', '.join(lines)}"])
    return {"name": PurePosixPath(lines[0]).name, "path": lines[0]} if lines else None


def git_hooks(tree: Tree) -> list[dict[str, str]]:
    """Each git hook a feature declares, which the install links into a main checkout's
    `.git/hooks/<name>`."""
    return [
        {"name": name, "path": script}
        for feature in tree.features
        for name, script in feature.git_hooks
    ]


def project_skills(tree: Tree) -> list[dict[str, str]]:
    """Each project skill a feature declares, by name, which the install links into the
    checkout's `.claude/skills/<name>` and `.cursor/skills/<name>`."""
    found = [
        {"name": name, "path": path}
        for feature in tree.features
        for name, path in feature.project_skills
    ]
    return sorted(found, key=lambda one: one["name"])


def text(tree: Tree) -> bytes:
    listed: dict[str, object] = {"$comment": COMMENT, "items": entries(tree), "hooks": hooks(tree)}
    line = status_line(tree)
    listed |= {"statusLine": line} if line else {}
    listed["gitHooks"] = git_hooks(tree)
    listed["projectSkills"] = project_skills(tree)
    return (json.dumps(listed, indent=2) + "\n").encode()


def render(tree: Tree) -> dict[str, bytes]:
    return {PATH: text(tree)}
