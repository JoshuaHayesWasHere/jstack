"""`harness/jstack/claude-code/`: the one copy of jstack's skills an agent is linked to, and
`harness/jstack/pythonpath`, the folders jstack's packages are imported from.

The copy holds every skill as `skills/<name>/`, flat, every playbook as `playbooks/<name>.md`,
every principle as `principles/<name>.md` (a stub that points at it, once a principle is a
skill), the templates but the systemd units, each hook a feature declares as `hooks/<file>`,
`plugin.json` twice and a README. `skills/` and `templates/` are siblings in it, as in the
checkout, so a skill that finds its templates through its own link still finds them. src/,
tests/, docs/ and the units stay in the checkout. Each Markdown file's relative links are
rewritten for the copy (`links`). The folder is written whole: a file in it that no item makes is
removed.
"""

from __future__ import annotations

import json
from pathlib import Path, PurePosixPath

from jtrees import links
from jtrees.check import File
from jtrees.crawl import PLUGIN, Invalid
from jtrees.model import Tree

HARNESS = "claude-code"
COPY = f"harness/jstack/{HARNESS}"
PYTHONPATH = "harness/jstack/pythonpath"
DIRS = (COPY,)
UNITS = (".service", ".timer")
# What a skill's folder holds that is not the skill: a feature's other parts, and its
# playbooks, which the copy puts in playbooks/.
NOT_THE_SKILL = frozenset(
    {"feature.json", "verify.md", "src", "tests", "docs", "evals", "templates", "hooks", "units"}
    | {"skills", "playbooks", "__pycache__"}
)
HEADER = (
    "<!-- generated by scripts/generate-jstack-trees.py from features/; do not edit; "
    "rerun: python3 scripts/generate-jstack-trees.py -->\n"
)


def _skill_files(root: Path, folder: str) -> list[str]:
    """Every file of a skill's folder, as repo paths, but what `NOT_THE_SKILL` names."""
    found = []
    for path in sorted((root / folder).rglob("*")):
        parts = path.relative_to(root / folder).parts
        if parts[0] in NOT_THE_SKILL or any(p.startswith(".") or p == "__pycache__" for p in parts):
            continue
        if path.is_file():
            found.append(path.relative_to(root).as_posix())
    return found


def _placed(tree: Tree) -> tuple[dict[str, str], dict[str, str]]:
    """Each repo file the copy holds, by where it goes in the copy; and each stub, by the
    principle skill it points at."""
    placed: dict[str, str] = {}
    stubs: dict[str, str] = {}
    for item in tree.items:
        path = PurePosixPath(item.path)
        if item.kind in ("skill", "principle") and path.name == "SKILL.md":
            for one in _skill_files(tree.root, str(path.parent)):
                placed[one] = f"skills/{item.name}/{PurePosixPath(one).relative_to(path.parent)}"
            if item.kind == "principle":
                stubs[f"principles/{item.name}.md"] = item.name
        elif item.kind == "principle":
            placed[item.path] = f"principles/{item.name}.md"
        elif item.kind == "playbook":
            placed[item.path] = f"playbooks/{item.name}.md"
        elif not item.name.endswith(UNITS):
            placed[item.path] = f"templates/{item.name}"
    for feature in tree.features:
        scripts = [one.script for one in feature.hooks] + [one for _, one in feature.git_hooks]
        for script in [*scripts, *([feature.status_line] if feature.status_line else [])]:
            placed[script] = f"hooks/{PurePosixPath(script).name}"
    placed[PLUGIN] = "plugin.json"
    return placed, stubs


def _stub(name: str) -> str:
    return f"# {name}\n\nThis principle is a skill: read [{name}](../skills/{name}/SKILL.md).\n"


def _readme(tree: Tree, placed: dict[str, str]) -> str:
    skills = sorted(
        (item.name, item.description)
        for item in tree.items
        if item.kind in ("skill", "principle") and item.path.endswith("/SKILL.md")
    )
    rows = "".join(
        f"| [{name}](skills/{name}/SKILL.md) | {' '.join(said.split()).replace('|', '/')} |\n"
        for name, said in skills
    )
    counts = {
        folder: sum(1 for one in set(placed.values()) if one.startswith(f"{folder}/"))
        for folder in ("playbooks", "principles", "templates", "hooks")
    }
    return (
        f"{HEADER}# jstack for Claude Code\n\n"
        "This folder is jstack as an agent reads it, made from the checkout's `features/` by "
        "`python3 scripts/generate-jstack-trees.py`. `install.sh` links each entry of "
        "`~/.claude/skills`, `~/.agents/skills` and `~/.codex/skills` to a folder of `skills/` "
        "here, and each hook command to a script of `hooks/`. An edit to a skill in the "
        "checkout reaches an agent once the generator has run.\n\n"
        f"It holds {len(skills)} skills, {counts['playbooks']} playbooks, "
        f"{counts['principles']} principles, {counts['templates']} templates and "
        f"{counts['hooks']} hooks. The code, the tests, the docs and the systemd units stay in "
        "the checkout.\n\n"
        "| Skill | What it is for |\n|---|---|\n"
        f"{rows}"
    )


def _pythonpath(tree: Tree) -> str:
    folders = {"src"} | {
        str(PurePosixPath(package).parent) for one in tree.features for package in one.packages
    }
    return "".join(f"{folder}\n" for folder in sorted(folders))


def render(tree: Tree) -> dict[str, File | bytes]:
    root = tree.root
    placed, stubs = _placed(tree)
    base = str(json.loads((root / PLUGIN).read_text(encoding="utf-8"))["repository"]).rstrip("/")
    want: dict[str, File | bytes] = {}
    faults: list[str] = []
    for source, copied in sorted(placed.items()):
        path = root / source
        content = path.read_bytes()
        if source.endswith(".md"):
            text, dangling = links.rewrite(
                content.decode("utf-8"), source, copied, placed, root, base
            )
            faults += [
                f"{COPY}/{copied} links to {href}, which is not in the tree" for href in dangling
            ]
            content = text.encode("utf-8")
        want[f"{COPY}/{copied}"] = File(content, bool(path.stat().st_mode & 0o100))
    if faults:
        raise Invalid(faults, prefix="FAIL ")
    for stub, name in stubs.items():
        want[f"{COPY}/{stub}"] = _stub(name).encode()
    want[f"{COPY}/.claude-plugin/plugin.json"] = want[f"{COPY}/plugin.json"]
    want[f"{COPY}/README.md"] = _readme(tree, placed).encode()
    want[PYTHONPATH] = _pythonpath(tree).encode()
    return want
